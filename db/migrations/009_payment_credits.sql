-- Stores the existing credits a Customer/Supplier Payment used (docs/ACCOUNTING.md) as payment lines, numbered after
-- its tenders, so the payment's "<Payment> - Detailed" report lists them alongside the tenders.
--
-- Backfills payments posted before this release from the allocation ledger: an allocation a payment made from a
-- credit that isn't one of its own tenders is a credit it used (reversed ones too — a voided payment still shows what
-- it posted). Idempotent: tables are created only if missing, and a payment that already has credit lines is skipped.

CREATE TABLE IF NOT EXISTS customer_payment_credits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount              NUMERIC(19, 2) NOT NULL,
    line_number         INTEGER NOT NULL,
    customer_payment_id BIGINT NOT NULL,
    credit_item_id      BIGINT NOT NULL,
    charge_item_id      BIGINT NOT NULL,
    CONSTRAINT CUSTOMER_PAYMENT_CREDITS_CUSTOMER_PAYMENT_ID_FK FOREIGN KEY (customer_payment_id) REFERENCES customer_payments(id) ON DELETE CASCADE,
    CONSTRAINT CUSTOMER_PAYMENT_CREDITS_CREDIT_ITEM_ID_FK FOREIGN KEY (credit_item_id) REFERENCES open_items(id),
    CONSTRAINT CUSTOMER_PAYMENT_CREDITS_CHARGE_ITEM_ID_FK FOREIGN KEY (charge_item_id) REFERENCES open_items(id)
);

CREATE TABLE IF NOT EXISTS supplier_payment_credits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount              NUMERIC(19, 2) NOT NULL,
    line_number         INTEGER NOT NULL,
    supplier_payment_id BIGINT NOT NULL,
    credit_item_id      BIGINT NOT NULL,
    charge_item_id      BIGINT NOT NULL,
    CONSTRAINT SUPPLIER_PAYMENT_CREDITS_SUPPLIER_PAYMENT_ID_FK FOREIGN KEY (supplier_payment_id) REFERENCES supplier_payments(id) ON DELETE CASCADE,
    CONSTRAINT SUPPLIER_PAYMENT_CREDITS_CREDIT_ITEM_ID_FK FOREIGN KEY (credit_item_id) REFERENCES open_items(id),
    CONSTRAINT SUPPLIER_PAYMENT_CREDITS_CHARGE_ITEM_ID_FK FOREIGN KEY (charge_item_id) REFERENCES open_items(id)
);

INSERT INTO customer_payment_credits (customer_payment_id, line_number, credit_item_id, charge_item_id, amount)
SELECT a.source_id,
       (SELECT count(*) FROM customer_payment_tenders t WHERE t.customer_payment_id = a.source_id)
           + row_number() OVER (PARTITION BY a.source_id ORDER BY a.id),
       a.credit_item_id, a.charge_item_id, a.amount
FROM open_item_allocations a
WHERE a.source_type = 'CUSTOMER_PAYMENT'
  AND NOT EXISTS (SELECT 1 FROM customer_payment_tenders t
                  WHERE t.customer_payment_id = a.source_id AND t.open_item_id = a.credit_item_id)
  AND NOT EXISTS (SELECT 1 FROM customer_payment_credits c WHERE c.customer_payment_id = a.source_id);

INSERT INTO supplier_payment_credits (supplier_payment_id, line_number, credit_item_id, charge_item_id, amount)
SELECT a.source_id,
       (SELECT count(*) FROM supplier_payment_tenders t WHERE t.supplier_payment_id = a.source_id)
           + row_number() OVER (PARTITION BY a.source_id ORDER BY a.id),
       a.credit_item_id, a.charge_item_id, a.amount
FROM open_item_allocations a
WHERE a.source_type = 'SUPPLIER_PAYMENT'
  AND NOT EXISTS (SELECT 1 FROM supplier_payment_tenders t
                  WHERE t.supplier_payment_id = a.source_id AND t.open_item_id = a.credit_item_id)
  AND NOT EXISTS (SELECT 1 FROM supplier_payment_credits c WHERE c.supplier_payment_id = a.source_id);
