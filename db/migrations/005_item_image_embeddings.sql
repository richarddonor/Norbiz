-- Item photo recognition (docs/ITEM_RECOGNITION.md): pgvector plus one CLIP embedding per item
-- reference image. Requires the db image built from Dockerfile.db (pgvector compiled in); on a plain
-- postgres image CREATE EXTENSION fails and the migration rolls back.
--
-- Not a JPA entity (it's a derived search index, written with JdbcTemplate), so Hibernate never
-- creates or validates it — no pre-existing Hibernate-shaped table to reconcile.
-- Idempotent: IF NOT EXISTS throughout.

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS item_image_embeddings (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT       NOT NULL,
    item_id    BIGINT       NOT NULL,
    image_path VARCHAR(500) NOT NULL,
    model      VARCHAR(100) NOT NULL,
    embedding  vector(512)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT ITEM_IMAGE_EMBEDDINGS_ITEM_IMAGE_UQ  UNIQUE (item_id, image_path),
    CONSTRAINT ITEM_IMAGE_EMBEDDINGS_COMPANY_ID_FK  FOREIGN KEY (company_id) REFERENCES companies(id),
    CONSTRAINT ITEM_IMAGE_EMBEDDINGS_ITEM_ID_FK     FOREIGN KEY (item_id)    REFERENCES items(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ITEM_IMAGE_EMBEDDINGS_COMPANY_MODEL_IX ON item_image_embeddings (company_id, model);
