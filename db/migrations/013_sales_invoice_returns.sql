-- Sales Invoice Return (docs/ACCOUNTING.md "Sales Invoice Return"): a customer returns items billed on its Sales Invoices
-- — stock back into the main warehouse, a RECEIVABLE CREDIT for what they were billed at. Invoice lines track how much
-- came back (quantity_loaded) and an invoice is loaded once fully returned. Zero-value Sales Invoices (no open item) are
-- allowed from this release on; nothing in the schema changes for that.
--
-- A local backend with ddl-auto=update may already have created any of this in Hibernate's shape (no DEFAULTs, nullable
-- columns): defaults and NOT NULL are set explicitly either way. The VIEW_/CREATE_/VOID_SALES_INVOICE_RETURN and detailed
-- report permissions are seeded by DataInitializer on startup — no rows needed here.

ALTER TABLE sales_invoices ADD COLUMN IF NOT EXISTS loaded BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE sales_invoices SET loaded = FALSE WHERE loaded IS NULL;
ALTER TABLE sales_invoices ALTER COLUMN loaded SET DEFAULT FALSE;
ALTER TABLE sales_invoices ALTER COLUMN loaded SET NOT NULL;

ALTER TABLE sales_invoice_lines ADD COLUMN IF NOT EXISTS quantity_loaded NUMERIC(19, 4) NOT NULL DEFAULT 0;
UPDATE sales_invoice_lines SET quantity_loaded = 0 WHERE quantity_loaded IS NULL;
ALTER TABLE sales_invoice_lines ALTER COLUMN quantity_loaded SET DEFAULT 0;
ALTER TABLE sales_invoice_lines ALTER COLUMN quantity_loaded SET NOT NULL;

CREATE TABLE IF NOT EXISTS sales_invoice_returns (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    net_amount       NUMERIC(19, 2) NOT NULL,
    voided           BOOLEAN NOT NULL DEFAULT FALSE,
    company_id       BIGINT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    customer_id      BIGINT NOT NULL,
    open_item_id     BIGINT UNIQUE,
    return_date      TIMESTAMPTZ NOT NULL,
    voided_at        TIMESTAMPTZ,
    warehouse_id     BIGINT NOT NULL,
    origin           VARCHAR(20) NOT NULL DEFAULT 'NATIVE',
    reference_number VARCHAR(50) NOT NULL,
    created_by       VARCHAR(100),
    sheet_number     VARCHAR(100),
    voided_by        VARCHAR(100),
    remarks          VARCHAR(255),
    CONSTRAINT SALES_INVOICE_RETURNS_COMPANY_REFERENCE_UQ UNIQUE (company_id, reference_number),
    CONSTRAINT SALES_INVOICE_RETURNS_COMPANY_ID_FK FOREIGN KEY (company_id) REFERENCES companies(id),
    CONSTRAINT SALES_INVOICE_RETURNS_CUSTOMER_ID_FK FOREIGN KEY (customer_id) REFERENCES customers(id),
    CONSTRAINT SALES_INVOICE_RETURNS_OPEN_ITEM_ID_FK FOREIGN KEY (open_item_id) REFERENCES open_items(id),
    CONSTRAINT SALES_INVOICE_RETURNS_WAREHOUSE_ID_FK FOREIGN KEY (warehouse_id) REFERENCES warehouses(id)
);

CREATE TABLE IF NOT EXISTS sales_invoice_return_lines (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_number             INTEGER NOT NULL,
    quantity                NUMERIC(19, 4) NOT NULL,
    unit_price              NUMERIC(19, 4) NOT NULL DEFAULT 0,
    posts_stock             BOOLEAN NOT NULL DEFAULT TRUE,
    item_id                 BIGINT NOT NULL,
    sales_invoice_line_id   BIGINT,
    sales_invoice_return_id BIGINT NOT NULL,
    CONSTRAINT SALES_INVOICE_RETURN_LINES_ITEM_ID_FK FOREIGN KEY (item_id) REFERENCES items(id),
    CONSTRAINT SALES_INVOICE_RETURN_LINES_SALES_INVOICE_LINE_ID_FK FOREIGN KEY (sales_invoice_line_id) REFERENCES sales_invoice_lines(id),
    CONSTRAINT SALES_INVOICE_RETURN_LINES_SALES_INVOICE_RETURN_ID_FK FOREIGN KEY (sales_invoice_return_id) REFERENCES sales_invoice_returns(id) ON DELETE CASCADE
);

ALTER TABLE sales_invoice_returns ALTER COLUMN voided SET DEFAULT FALSE;
ALTER TABLE sales_invoice_returns ALTER COLUMN created_at SET DEFAULT NOW();
ALTER TABLE sales_invoice_returns ALTER COLUMN origin SET DEFAULT 'NATIVE';
ALTER TABLE sales_invoice_return_lines ALTER COLUMN unit_price SET DEFAULT 0;
UPDATE sales_invoice_return_lines SET posts_stock = TRUE WHERE posts_stock IS NULL;
ALTER TABLE sales_invoice_return_lines ALTER COLUMN posts_stock SET DEFAULT TRUE;
ALTER TABLE sales_invoice_return_lines ALTER COLUMN posts_stock SET NOT NULL;

-- Hibernate's enum CHECK on origin, if a local backend created the table.
DO $$
DECLARE
    c RECORD;
BEGIN
    FOR c IN SELECT conrelid::regclass::text AS tbl, conname FROM pg_constraint
             WHERE contype = 'c' AND conname LIKE '%\_check'
               AND conrelid::regclass::text IN ('sales_invoice_returns', 'sales_invoice_return_lines')
    LOOP
        EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', c.tbl, c.conname);
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS SALES_INVOICE_RETURN_LINES_RETURN_IDX ON sales_invoice_return_lines (sales_invoice_return_id);
CREATE INDEX IF NOT EXISTS SALES_INVOICE_RETURN_LINES_INVOICE_LINE_IDX ON sales_invoice_return_lines (sales_invoice_line_id);
CREATE INDEX IF NOT EXISTS SALES_INVOICE_RETURNS_COMPANY_DATE_IDX ON sales_invoice_returns (company_id, return_date);
CREATE INDEX IF NOT EXISTS SALES_INVOICE_RETURNS_CUSTOMER_IDX ON sales_invoice_returns (customer_id);
