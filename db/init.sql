    action_definition_id BIGINT NOT NULL,
    role_id              BIGINT NOT NULL,
    PRIMARY KEY (action_definition_id, role_id),
    CONSTRAINT TXN_ACTION_DEF_ROLES_DEF_ID_FK  FOREIGN KEY (action_definition_id) REFERENCES transaction_action_definitions(id) ON DELETE CASCADE,
    CONSTRAINT TXN_ACTION_DEF_ROLES_ROLE_ID_FK FOREIGN KEY (role_id)              REFERENCES roles(id)
