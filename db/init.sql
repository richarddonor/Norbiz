ALTER TABLE warehouses ADD COLUMN IF NOT EXISTS outlet BOOLEAN NOT NULL DEFAULT FALSE;
CREATE UNIQUE INDEX IF NOT EXISTS WAREHOUSES_COMPANY_MAIN_UQ ON warehouses (company_id) WHERE main;

-- OUTLET customers' own warehouse (auto-created by the app; own identity id, not the customer id).
ALTER TABLE customers ADD COLUMN IF NOT EXISTS warehouse_id BIGINT;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'customers_warehouse_id_fk') THEN
        ALTER TABLE customers ADD CONSTRAINT CUSTOMERS_WAREHOUSE_ID_FK FOREIGN KEY (warehouse_id) REFERENCES warehouses(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'customers_warehouse_uq') THEN
        ALTER TABLE customers ADD CONSTRAINT CUSTOMERS_WAREHOUSE_UQ UNIQUE (warehouse_id);
    END IF;
END $$;

