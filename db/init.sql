-- ============================================================
-- Purchase Receives — Supplier is the counterparty (copied from the source). Posted against the
-- outstanding intransit quantity of either a Purchase Order or a Direct-mode Purchase Invoice
-- (exactly one of purchase_order_id / purchase_invoice_id is set, enforced in the service layer,
-- not by a DB constraint, matching this codebase's existing convention). No unique constraint on
-- either FK: a source can be received across multiple partial Purchase Receives.
-- Posting deducts Transit Quantity and adds to main Quantity; voiding reverses it.
-- See docs/TRANSACTIONS.md "Purchase Receive" / "Voiding".
-- ============================================================

CREATE TABLE IF NOT EXISTS purchase_receives (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          BIGINT      NOT NULL,
    warehouse_id        BIGINT      NOT NULL,
    supplier_id         BIGINT      NOT NULL,
