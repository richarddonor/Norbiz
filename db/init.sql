    CONSTRAINT TXN_EVENTS_ACTION_DEFINITION_ID_FK FOREIGN KEY (action_definition_id) REFERENCES transaction_action_definitions(id)
);

CREATE INDEX IF NOT EXISTS TXN_EVENTS_TRANSACTION_IDX ON transaction_events (transaction_type, transaction_id, performed_at);

